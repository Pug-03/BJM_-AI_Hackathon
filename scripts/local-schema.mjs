// Generates prisma/.local.prisma — the same schema without pgvector — for local
// Postgres installs that lack the extension. The app detects the missing
// `embedding` columns at runtime and falls back to non-vector matching.
import fs from "fs";
const src = fs.readFileSync("prisma/schema.prisma", "utf8");
const out = src
  .replace(/\n\s*previewFeatures\s*=.*\n/, "\n")
  .replace(/\n\s*extensions\s*=.*\n/, "\n")
  .split("\n")
  .filter((l) => !/Unsupported\("vector/.test(l))
  .join("\n");
fs.writeFileSync("prisma/.local.prisma", "// GENERATED by scripts/local-schema.mjs — do not edit\n" + out);
console.log("wrote prisma/.local.prisma");
